export function translate(locale: Locale, source: string): string {
  return locale === 'en' ? english[source] ?? source : source;
}
export function remainingLabel(locale: Locale, remaining: number, kind: 'certificate' | 'receipt') {
  if (locale === 'en') return `${remaining} more to ${kind === 'certificate' ? 'unlock' : 'record'}`;
  return `あと${remaining}つで${kind === 'certificate' ? '解放' : '記録'}`;
}
